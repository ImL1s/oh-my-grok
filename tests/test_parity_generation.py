def _load_generator():
    spec = importlib.util.spec_from_file_location(
        "generate_parity_docs",
        ROOT / "scripts" / "generate_parity_docs.py",
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _run_generate_check() -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "scripts/generate_parity_docs.py", "--check"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )


def _assert_no_overclaim(text: str) -> None:
    assert "%" not in text
    assert "✅" not in text
    assert "✓" not in text


def test_generated_feature_matrix_is_current() -> None:
    result = _run_generate_check()
    assert result.returncode == 0, result.stderr
    text = MATRIX.read_text(encoding="utf-8")
    assert "GENERATED by scripts/generate_parity_docs.py" in text
    assert "bootstrapping" in text.lower()
    _assert_no_overclaim(text)
    inventory = validate_parity_inventory(load_json_object(INVENTORY), repo_root=ROOT)
    for row in inventory["capabilities"]:
        assert f"`{row['id']}`" in text


_OPEN_P0_BULLET = re.compile(r"^- `([^`]+)` \(([^)]+)\):", re.MULTILINE)
_GAPS_TABLE_ROW = re.compile(
    r"^\| `([^`]+)` \| (P[0-9]) \| (open|closed|deferred) \| ([^|]+) \|",
    re.MULTILINE,
)


def _open_p0_section(text: str) -> str:
    _, found, rest = text.partition("## Open P0")
    assert found, "generated GAPS.md missing ## Open P0"
    return rest


