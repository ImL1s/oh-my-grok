def test_parity_readme_snapshot_projects_inventory_contract() -> None:
    gen = _load_generator()
    inventory = validate_parity_inventory(load_json_object(INVENTORY), repo_root=ROOT)
    snap = gen.render_parity_readme_snapshot(inventory)
    _assert_no_overclaim(snap)

    assert f"| `store_kind` | `{inventory['store_kind']}` |" in snap
    assert f"| `schema_version` | `{inventory['schema_version']}` |" in snap
    assert f"| `repository_id` | `{inventory['repository_id']}` |" in snap
    assert (
        f"| `ownership_manifest_id` | `{inventory['ownership_manifest_id']}` |" in snap
    )
    assert f"| `inventory_status` | `{inventory['inventory_status']}` |" in snap
    assert (
        f"| `live_evidence_max_age_days` | `{inventory['live_evidence_max_age_days']}` |"
        in snap
    )
    assert f"| Capabilities catalogued | {len(inventory['capabilities'])} |" in snap
    open_gaps = [g for g in inventory["gaps"] if g.get("status") == "open"]
    assert f"| Open gaps | {len(open_gaps)} |" in snap

    for source in SOURCE_STATUS_IDS:
        status = inventory["source_status"][source]
        assert f"| `{source}` | `{status}` |" in snap

    for name, status in sorted(inventory["category_status"].items()):
        assert f"| `{name}` | `{status}` |" in snap

    from omg_cli.contracts.parity_schema import HOST_BASELINE_PIN_ID, UPSTREAM_PIN_IDS

    assert HOST_BASELINE_PIN_ID in snap
    for pin_id in UPSTREAM_PIN_IDS:
        pin = inventory["upstream_pins"][pin_id]
        assert (
            f"| `{pin_id}` | `{pin['repository']}` | `{pin['revision']}` | `{pin['kind']}` |"
            in snap
        )

    maturity = " → ".join(f"`{level}`" for level in inventory["maturity_levels"])
    assert maturity in snap
    classifications = ", ".join(f"`{item}`" for item in inventory["classifications"])
    assert classifications in snap

    from collections import Counter

    from omg_cli.contracts.parity_schema import max_runtime_maturity

    by_maturity: Counter[str] = Counter()
    for row in inventory["capabilities"]:
        by_maturity[max_runtime_maturity(row)] += 1
    for level, count in by_maturity.items():
        assert f"| `{level}` | {count} |" in snap


def test_parity_readme_snapshot_drift_fails_closed() -> None:
    gen = _load_generator()
    inventory = validate_parity_inventory(load_json_object(INVENTORY), repo_root=ROOT)
    mutated = dict(inventory)
    mutated["inventory_status"] = (
        "complete" if inventory["inventory_status"] != "complete" else "bootstrapping"
    )
    # Bypass full re-validation: render from mutated header field only.
    expected_current = gen.render_parity_readme_snapshot(inventory).rstrip("\n")
    drifted = gen.render_parity_readme_snapshot(mutated).rstrip("\n")
    assert drifted != expected_current

    text = (ROOT / "docs/parity/README.md").read_text(encoding="utf-8")
    _prefix, interior, _suffix = gen.split_managed_block(
        text,
        begin=gen.PARITY_README_SNAPSHOT_BEGIN,
        end=gen.PARITY_README_SNAPSHOT_END,
        label="docs/parity/README.md",
    )
    assert interior.rstrip("\n") == expected_current
    assert interior.rstrip("\n") != drifted

    # Simulate stale README interior against mutated inventory expectation.
    stale_text = gen.apply_managed_block(
        text,
        expected_current + "\n",
        begin=gen.PARITY_README_SNAPSHOT_BEGIN,
        end=gen.PARITY_README_SNAPSHOT_END,
        label="docs/parity/README.md",
    )
    _p, stale_interior, _s = gen.split_managed_block(
        stale_text,
        begin=gen.PARITY_README_SNAPSHOT_BEGIN,
        end=gen.PARITY_README_SNAPSHOT_END,
        label="docs/parity/README.md",
    )
    assert stale_interior.rstrip("\n") != drifted


def test_parity_readme_snapshot_markers_fail_closed() -> None:
    gen = _load_generator()
    from omg_cli.contracts.state_schemas import ContractValidationError

    begin = gen.PARITY_README_SNAPSHOT_BEGIN
    end = gen.PARITY_README_SNAPSHOT_END
    label = "docs/parity/README.md"

    with pytest.raises(ContractValidationError, match="malformed managed markers"):
        gen.split_managed_block("no markers here", begin=begin, end=end, label=label)

    with pytest.raises(ContractValidationError, match="malformed managed markers"):
        gen.split_managed_block(
            f"{begin}\nbody\n{end}\n{begin}\nagain\n{end}",
            begin=begin,
            end=end,
            label=label,
        )

    with pytest.raises(ContractValidationError, match="end precedes begin"):
        gen.split_managed_block(
            f"{end}\nbody\n{begin}",
            begin=begin,
            end=end,
            label=label,
        )


def test_parity_readme_snapshot_update_is_idempotent_and_preserves_prose() -> None:
    gen = _load_generator()
    path = ROOT / "docs/parity/README.md"
    original = path.read_text(encoding="utf-8")
    prefix, interior, suffix = gen.split_managed_block(
        original,
        begin=gen.PARITY_README_SNAPSHOT_BEGIN,
        end=gen.PARITY_README_SNAPSHOT_END,
        label="docs/parity/README.md",
    )
    assert "Machine-readable claimability contract" in prefix
    assert "## Migration" in suffix or "Migration" in suffix

    inventory = validate_parity_inventory(load_json_object(INVENTORY), repo_root=ROOT)
    expected = gen.render_parity_readme_snapshot(inventory).rstrip("\n") + "\n"
    once = gen.apply_managed_block(
        original,
        expected,
        begin=gen.PARITY_README_SNAPSHOT_BEGIN,
        end=gen.PARITY_README_SNAPSHOT_END,
        label="docs/parity/README.md",
    )
    twice = gen.apply_managed_block(
        once,
        expected,
        begin=gen.PARITY_README_SNAPSHOT_BEGIN,
        end=gen.PARITY_README_SNAPSHOT_END,
        label="docs/parity/README.md",
    )
    assert once == twice
    once_prefix, once_interior, once_suffix = gen.split_managed_block(
        once,
        begin=gen.PARITY_README_SNAPSHOT_BEGIN,
        end=gen.PARITY_README_SNAPSHOT_END,
        label="docs/parity/README.md",
    )
    assert once_prefix == prefix
    assert once_suffix == suffix
    assert once_interior.rstrip("\n") == expected.rstrip("\n")
    # Hand-authored semantics remain; no duplicate hard-coded progress slogans.
    prose = once_prefix + once_suffix
    assert "#78-C landed" not in prose
    assert "#78-D landed" not in prose


def test_generate_check_covers_readme_managed_snapshot() -> None:
    gen = _load_generator()
    assert gen.README_PATH in gen.MANAGED_BLOCK_PATHS
    assert gen.README_PATH not in gen.GENERATED_PATHS
    result = _run_generate_check()
    assert result.returncode == 0, result.stderr
    assert "ok" in result.stdout

    text = (ROOT / "docs/parity/README.md").read_text(encoding="utf-8")
    # Force drift by rewriting interior via apply then mutating a field line.
    inventory = validate_parity_inventory(load_json_object(INVENTORY), repo_root=ROOT)
    good = gen.render_parity_readme_snapshot(inventory).rstrip("\n") + "\n"
    drifted_interior = good.replace(
        f"| `inventory_status` | `{inventory['inventory_status']}` |",
        "| `inventory_status` | `complete` |",
        1,
    )
    drifted = gen.apply_managed_block(
        text,
        drifted_interior,
        begin=gen.PARITY_README_SNAPSHOT_BEGIN,
        end=gen.PARITY_README_SNAPSHOT_END,
        label="docs/parity/README.md",
    )
    path = ROOT / "docs/parity/README.md"
    try:
        path.write_text(drifted, encoding="utf-8")
        failed = _run_generate_check()
        assert failed.returncode != 0
        assert "stale managed artifact" in failed.stderr
        assert "docs/parity/README.md" in failed.stderr
    finally:
        path.write_text(text, encoding="utf-8")
